export function resolveLocale(language?: string | null, systemLanguage?: string): AppLocale {
    if (language === "en-US" || language === "zh-CN") {
        return language;
    }
    if (language == null || language === "") {
        return "zh-CN";
    }
    const detected = systemLanguage ?? (typeof navigator !== "undefined" ? navigator.language : "zh-CN");
    return detected.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

export function translate(locale: AppLocale, message: string, values?: TranslationValues): string {
    let translated = locale === "zh-CN" ? (zhCN[message] ?? message) : message;
    if (values) {
        for (const [key, value] of Object.entries(values)) {
            translated = translated.split(`{{${key}}}`).join(String(value));
        }
    }
    return translated;
}

export function languageDisplayName(language: AppLanguage, locale: AppLocale): string {
    if (language === "auto") return translate(locale, "Follow system");
    if (language === "zh-CN") return "简体中文";
    return "English";
}
